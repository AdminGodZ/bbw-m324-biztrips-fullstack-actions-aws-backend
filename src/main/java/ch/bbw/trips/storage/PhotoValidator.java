package ch.bbw.trips.storage;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.UUID;
import org.springframework.http.HttpStatus;
import org.springframework.web.multipart.MultipartFile;
import org.springframework.web.server.ResponseStatusException;

/** Storage-independent upload validation shared by the local and the S3 implementation. */
public final class PhotoValidator {
    public static final long MAX_BYTES = 5 * 1024 * 1024;
    private static final String NAME_PATTERN = "[a-f0-9-]{36}\\.(png|jpg|webp)";
    private static final byte[] PNG_MAGIC = {(byte) 137, 80, 78, 71, 13, 10, 26, 10};

    private PhotoValidator() {
    }

    /** A validated upload: the bytes plus the generated, safe file name. */
    public record ValidatedPhoto(String filename, byte[] bytes, String contentType) {
    }

    public static ValidatedPhoto validate(MultipartFile file) throws IOException {
        if (file == null || file.isEmpty()) throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Empty file");
        if (file.getSize() > MAX_BYTES) throw new ResponseStatusException(HttpStatus.PAYLOAD_TOO_LARGE);
        byte[] bytes;
        try (var in = file.getInputStream()) {
            bytes = in.readNBytes((int) MAX_BYTES + 1);
        }
        if (bytes.length > MAX_BYTES) throw new ResponseStatusException(HttpStatus.PAYLOAD_TOO_LARGE);
        String type = file.getContentType();
        String extension;
        if ("image/png".equals(type) && bytes.length >= 8 && Arrays.equals(Arrays.copyOf(bytes, 8), PNG_MAGIC)) {
            extension = ".png";
        } else if ("image/jpeg".equals(type) && bytes.length >= 3 && (bytes[0] & 255) == 255
                && (bytes[1] & 255) == 216 && (bytes[2] & 255) == 255) {
            extension = ".jpg";
        } else if ("image/webp".equals(type) && bytes.length >= 12
                && new String(bytes, 0, 4, StandardCharsets.US_ASCII).equals("RIFF")
                && new String(bytes, 8, 4, StandardCharsets.US_ASCII).equals("WEBP")) {
            extension = ".webp";
        } else {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Expected PNG, JPEG or WebP image data");
        }
        String filename = UUID.randomUUID() + extension;
        return new ValidatedPhoto(filename, bytes, contentType(filename));
    }

    /** Rejects anything that is not a name generated by {@link #validate}. Prevents path/key traversal. */
    public static String requireValidName(String filename) {
        if (filename == null || !filename.matches(NAME_PATTERN))
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Invalid storage reference");
        return filename;
    }

    public static String contentType(String filename) {
        requireValidName(filename);
        return filename.endsWith(".png") ? "image/png" : filename.endsWith(".webp") ? "image/webp" : "image/jpeg";
    }
}
